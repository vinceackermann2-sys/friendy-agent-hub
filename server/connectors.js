async function setupResult(userId, args) {
  const c = await findSetup(userId, args);
  if (!c) throw badInput(`${clean(args.name, 60) || 'The connector'} was not added. Ask the owner before trying again.`);
  const enabled = permissionsOf(c).filter((p) => p.enabled).map((p) => p.slug);
  return { added: true, connector: c.slug, name: c.name, kind: c.kind === 'mcp' ? 'MCP server' : 'API', status: c.status,
    ...(c.kind === 'mcp' ? { tools: enabled.slice(0, 40) } : { methods: enabled }),
    note: 'Connected. See what it can do with connector_tools and use it with connector_call.' };
}
async function forAgent(userId) {
  return (await store.listCustomConnectors(userId)).map((c) => ({
    connector: c.slug, name: c.name, kind: c.kind === 'mcp' ? 'MCP server' : 'API', host: hostOf(c.url),
    ...(c.description ? { about: c.description.slice(0, 240) } : {}),
    ...(c.status === 'error' ? { problem: c.lastError || 'The last check failed.' } : {}),
  }));
}
async function describe(userId, ref, query = '') {
  const c = await find(userId, ref);
  const perms = permissionsOf(c).filter((p) => p.enabled);
  if (c.kind === 'api') {
    const root = new URL(c.url);
    return {
      connector: c.slug, name: c.name, kind: 'API', baseUrl: `${root.origin}${basePathOf(root)}`,
      methods: perms.map((p) => p.slug), ...(c.description ? { about: c.description } : {}), ...(c.config?.docsUrl ? { docs: c.config.docsUrl } : {}),
      note: `Call connector_call with method and a path after the base URL. The credential is added for you.${c.config?.docsUrl ? ' Read the docs link with web_search for endpoints you do not know.' : ''} Methods not listed are turned off by the owner.`,
    };
  }
  const words = String(query || '').toLowerCase().split(/[^a-z0-9]+/).filter((w) => w.length > 2);
  const score = (t) => words.reduce((n, w) => n + (t.name.toLowerCase().includes(w) ? 3 : `${t.title} ${t.description}`.toLowerCase().includes(w) ? 1 : 0), 0);
  const enabled = new Set(perms.map((p) => p.slug));
  const tools = c.tools.filter((t) => enabled.has(t.name)).map((t, i) => [score(t), i, t]).sort((a, b) => b[0] - a[0] || a[1] - b[1]).map(([, , t]) => t);
  return {
    connector: c.slug, name: c.name, kind: 'MCP server', ...(c.description ? { about: c.description } : {}),
    tools: tools.slice(0, 40).map((t, i) => ({ name: t.name, kind: t.kind, description: t.description.split(/(?<=\.)\s/)[0].slice(0, 200), ...(i < 6 || words.length && score(t) > 0 && i < 12 ? { arguments: t.args } : {}) })),
    ...(tools.length > 40 ? { more: `${tools.length - 40} more tools; pass query to rank them.` } : {}),
    note: 'Call connector_call with tool and arguments. Tools not listed are turned off by the owner.',
  };
}
// What a call does, for the approval policy: 'read' or 'write'.
async function callKind(userId, args = {}) {
  const c = await find(userId, args.connector);
  if (c.kind === 'api') return API_METHODS.find((m) => m.slug === String(args.method || 'GET').toUpperCase())?.kind || 'write';
  return c.tools.find((t) => t.name === String(args.tool || ''))?.kind || 'write';
}
async function approvalDetail(userId, args = {}) {
  let c = null;
  try { c = await find(userId, args.connector); } catch {}
  const name = c ? c.name : clean(args.connector, 60) || 'your connector';
  if (!c || c.kind === 'mcp') {
    const tool = c?.tools.find((t) => t.name === args.tool);
    const input = args.arguments && typeof args.arguments === 'object' ? args.arguments : {};
    return JSON.stringify({ connector: c?.slug || args.connector, appName: name, action: tool?.title || humanize(args.tool) || 'Use a tool',
      fields: Object.entries(input).filter(([, value]) => value != null && value !== '').slice(0, 10).map(([k, value]) => ({ k: humanize(k), v: String(typeof value === 'object' ? JSON.stringify(value) : value).slice(0, 600) })),
      summary: `${humanize(args.tool) || 'Use a tool'} in ${name}` });
  }
  const method = String(args.method || 'GET').toUpperCase();
  let where = '';
  try { const u = new URL(apiUrl(c.url, args.path, args.query)); where = u.pathname + u.search; } catch { where = String(args.path || '/'); }
  const fields = [{ k: 'Request', v: `${method} ${where}`.slice(0, 600) }];
  if (args.body != null && !['GET', 'DELETE'].includes(method)) fields.push({ k: 'Body', v: (typeof args.body === 'string' ? args.body : JSON.stringify(args.body)).slice(0, 600) });
  const verb = { GET: 'Read from', POST: 'Send to', PUT: 'Replace in', PATCH: 'Update in', DELETE: 'Delete in' }[method] || 'Use';
  return JSON.stringify({ connector: c.slug, appName: name, action: `${verb} API`, fields, summary: `${method} ${where} on ${name}` });
}
async function call(userId, args = {}, { signal } = {}) {
  const c = await find(userId, args.connector);
  const perms = permissionsOf(c);
  const secret = await secretFor(userId, c);
  const sig = timeoutSignal(c.kind === 'mcp' ? 60000 : 30000, signal);
  let result, label;
  try {
    if (c.kind === 'mcp') {
      const name = String(args.tool || '').trim();
      if (!name) throw badInput('tool is required: a tool name from connector_tools.');
      const perm = perms.find((p) => p.slug === name);
      if (!perm) throw badInput(`${c.name} has no tool ${name}. Use connector_tools to see its tools.`);
      if (!perm.enabled) throw Object.assign(new Error(`The owner turned off ${perm.name} for ${c.name}.`), { code: 'PERMISSION_OFF' });
      const argsIn = args.arguments && typeof args.arguments === 'object' ? args.arguments : (args.args && typeof args.args === 'object' ? args.args : {});
      const session = await openMcp(c, secret, sig);
      let out;
      try { out = await session.request('tools/call', { name, arguments: argsIn }); } finally { session.close(); }
      const text = mcpContent(out);
      if (out?.isError) throw Object.assign(new Error((text || 'The tool reported an error.').slice(0, 600)), { code: 'MCP_ERROR' });
      result = { ...(out?.structuredContent ? { data: out.structuredContent } : {}), ...(text ? { text } : {}) };
      label = `${c.slug} ${name}`;
    } else {
      const method = String(args.method || 'GET').toUpperCase();
      const perm = perms.find((p) => p.slug === method);
      if (perm && !perm.enabled) throw Object.assign(new Error(`The owner turned off ${method} requests for ${c.name}.`), { code: 'PERMISSION_OFF' });
      result = await callApi(c, secret, args, sig);
      if (result.status === 401 || result.status === 403) throw Object.assign(new Error(result.note), { code: 'AUTH_FAILED', result });
      label = `${c.slug} ${method} ${result.status}`;
    }
  } catch (caught) {
    const error = reachError(caught, c.url);
    if (error.code === 'AUTH_FAILED' && c.status !== 'error') await store.updateCustomConnector(userId, c.id, { status: 'error', lastError: clean(error.message, 300), checkedAt: Date.now() }).catch(() => {});
    if (error.result) return { label: `${c.slug} refused`, result: compactResult(scrub(error.result, secret, c.config?.auth)) };
    error.message = String(scrub(error.message, secret, c.config?.auth));
    throw error;
  }
  if (c.status === 'error' || !c.checkedAt) await store.updateCustomConnector(userId, c.id, { status: 'connected', lastError: '', checkedAt: Date.now() }).catch(() => {});
  return { label, result: compactResult(scrub(result, secret, c.config?.auth)) };
}

