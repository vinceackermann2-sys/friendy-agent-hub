/* The owner's own connectors: REST APIs and remote MCP servers they add themselves.
   - The credential is a vault secret (AES-256-GCM, see store.js). A connector keeps only
     the secret's id; the value is read here for one request and never reaches the model.
     Results are scrubbed of it in case a server echoes it back.
   - Requests go from the server, not the VM: the VM's job containers have no network.
     Every address must be public https, checked again on each redirect, so a connector
     cannot reach loopback, private networks or cloud metadata.
   - MCP: Streamable HTTP, falling back to the older HTTP+SSE transport.
   - Permissions: each MCP tool, and each HTTP method of an API, can be turned off. Reads
     run when the owner asks; writes follow the connected-app approval setting.
   The edge copy in src/lingon-server/ is generated by scripts/sync-lingon.mjs. */
