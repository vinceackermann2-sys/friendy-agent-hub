// Matched against foldText output (ASCII), across the same languages as TOOL_KEYWORDS.
const PERSONAL_KEYWORDS = {
  goals: /(goal|milestone|habit|resolution|objective|progress|\bmal(et|en)?\b|delmal|\bmaal\b|\bziel|objectif|\bmeta\b|\bmetas\b|objetivo)/,
  library: /(library|artifact|artefakt|bibliotek|bibliothe|biblioteca|my (files|documents|images|photos|pictures|videos|uploads)|uploaded|saved (file|document|image|page)|rename|mina filer|mine filer|meine dateien|mes fichiers|mis archivos)/,
};
function pickPersonalTools(foldedTask) {
  const names = [];
  if (PERSONAL_KEYWORDS.goals.test(foldedTask)) names.push('goal_list', 'goal_create', 'goal_update', 'goal_delete');
  if (PERSONAL_KEYWORDS.library.test(foldedTask)) names.push('library_list', 'library_read', 'library_save', 'library_rename', 'library_delete');
  return names;
}

// Pages, Canvas files and generated images are real artifacts: keep a copy in
// the Library and tag the result so its chat card links to that Library item.
// A Library failure never fails the tool that produced the artifact.
function withLibraryAutosave(tools) {
  const capture = {
    build_page: (out) => out?.html && { title: 'your-page.html', mime: 'text/html', kind: 'web', content: out.html },
    canvas_show: (out) => {
      if (!out?.title || !out.content) return null;
      const ext = { md: 'md', html: 'html', json: 'json', csv: 'csv', svg: 'svg' }[out.format] || 'txt';
      const [mime, kind] = LIBRARY_FORMATS[ext];
      return { title: /\.[a-z0-9]{2,5}$/i.test(out.title) ? out.title : `${out.title}.${ext}`, mime, kind, content: out.content };
    },
    image_generate: (out) => out?.dataUrl && { title: out.name || 'generated.png', mime: out.mimeType || 'image/png', kind: 'image', content: out.dataUrl },
  };
  for (const [name, toItem] of Object.entries(capture)) {
    const tool = tools[name];
    if (!tool || tool.libraryAutosave) continue;
    const run = tool.run;
    tools[name] = { ...tool, libraryAutosave: true, run: async (args, ctx) => {
      const out = await run(args, ctx);
      const item = toItem(out);
      if (!item) return out;
      try {
        const saved = await store.saveLibraryItem(ctx.userId, { ...item, source: 'agent', chatId: ctx.chatId || ctx.sessionId });
        return { ...out, libraryId: saved.id };
      } catch (error) {
        ctx.trace?.(entry('library', `library autosave skipped: ${error.message}`));
        return out;
      }
    } };
  }
  return tools;
}

// Chat card for a goal or Library change, so the app refreshes that view and
// shows the owner what changed. Read-only calls produce no card.
function personalResultCard(name, out) {
  if (!out || out.error || !out.action) return null;
  if (name.startsWith('goal_')) {
    const steps = Array.isArray(out.steps) ? out.steps : [];
    return { type: 'goal', action: out.action, goalId: out.id, title: out.title, category: out.category || null,
      goalStatus: out.status || null, stepsDone: steps.filter((st) => st.done).length, stepsTotal: steps.length, status: 'done' };
  }
  if (name.startsWith('library_')) return { type: 'library', action: out.action, libraryId: out.id, title: out.title, kind: out.kind || null, status: 'done' };
  return null;
}
