const assert=require('node:assert/strict');
const fs=require('node:fs');
const {randomUUID}=require('node:crypto');
const {PGlite}=require('@electric-sql/pglite');

(async()=>{
  const db=new PGlite();
  await db.exec("create role anon;create role authenticated;create role service_role;create table profiles(id text primary key);insert into profiles values('a'),('b');");
  const sql=fs.readFileSync(require.resolve('../supabase/migrations/20260919160000_chat_tasks.sql'),'utf8');
  await db.exec(sql.split('-- Hosted recovery pump.')[0]);
  const query=async(sql,args=[]) => (await db.query(sql,args)).rows;
  const ids=[randomUUID(),randomUUID(),randomUUID()];
  const state={title:'Research',instructions:'Brief',status:'queued',version:1,events:[],summary:'',pending:[]};
  for(let i=0;i<3;i++) await query('select * from create_chat_task($1,$2,$3,$4,$5)',[ids[i],'a','chat',`req${i}`,state]);
  const duplicate=await query('select * from create_chat_task($1,$2,$3,$4,$5)',[randomUUID(),'a','chat','req0',state]);
  assert.equal(duplicate[0].id,ids[0]);
  const token1=randomUUID(),token2=randomUUID();
  const first=(await query('select * from claim_chat_task($1,$2,$3)',[ids[0],'a',token1]))[0];
  assert.equal((await query('select * from claim_chat_task($1,$2,$3)',[ids[0],'a',randomUUID()])).length,0,'one claim per task');
  assert.equal((await query('select * from claim_chat_task($1,$2,$3)',[ids[1],'b',randomUUID()])).length,0,'owner isolation');
  assert.equal((await query('select * from claim_chat_task($1,$2,$3)',[ids[1],'a',token2])).length,1);
  assert.equal((await query('select * from claim_chat_task($1,$2,$3)',[ids[2],'a',randomUUID()])).length,0,'at most two workers per owner');
  const changed={...state,version:2,status:'running',events:[{seq:1,type:'card',card:{type:'progress',label:'Verified'}}],system:'SECRET CONTEXT',observations:['LARGE OUTPUT']};
  assert.equal((await query('select * from write_chat_task($1,$2,$3,$4,$5)',[ids[0],'a',first.revision,randomUUID(),changed])).length,0,'wrong lease rejected');
  const written=(await query('select * from write_chat_task($1,$2,$3,$4,$5)',[ids[0],'a',first.revision,null,changed]))[0];
  assert.equal((await query('select * from write_chat_task($1,$2,$3,$4,$5)',[ids[0],'a',first.revision,token1,state])).length,0,'late worker cannot overwrite steering');
  assert.equal(written.state.version,2);
  let listed=await query('select * from list_chat_tasks($1,$2,$3,$4)',['a','chat',{[ids[0]]:1},true]);
  assert.equal(listed[0].state.events.length,0,'events delivered incrementally');
  assert.equal(listed[0].state.eventCount,1);
  assert.equal(listed[0].state.system,undefined);
  assert.equal(listed[0].state.observations,undefined);
  assert.equal((await query('select * from list_chat_tasks($1,$2,$3,$4)',['b','chat',{},true])).length,0);
  await query('select release_chat_task($1,$2,$3)',[ids[0],'a',randomUUID()]);
  assert.equal((await query('select lease_token from agent_chat_tasks where id=$1',[ids[0]]))[0].lease_token,token1);
  for(let i=0;i<2;i++) await query('select release_chat_task($1,$2,$3)',[ids[i],'a',i?token2:token1]);
  await query("update agent_chat_tasks set state=jsonb_set(state,'{pending}',$1)",[[{name:'shell'}]]);
  assert.equal((await query('select * from claim_chat_task($1,$2,$3)',[ids[0],'a',token1])).length,1);
  assert.equal((await query('select * from claim_chat_task($1,$2,$3)',[ids[1],'a',token2])).length,0,'VM commands serialize across task workers');
  await query("update agent_chat_tasks set state=jsonb_set(state,'{pending}','[]') where id=$1",[ids[1]]);
  assert.equal((await query('select * from claim_chat_task($1,$2,$3)',[ids[1],'a',token2])).length,1,'model work overlaps VM work');
  await db.exec('set role authenticated');
  await assert.rejects(query('select * from agent_chat_tasks'),/permission denied/);
  await assert.rejects(query('select * from list_chat_tasks($1,$2,$3,$4)',['a','chat',{},true]),/permission denied/);
  await db.close();
  console.log('chat tasks SQL: claims, CAS, owner isolation, exact cursors, VM serialization, service-only access: ok');
})().catch(e=>{console.error(e);process.exitCode=1;});
